import assert from 'node:assert/strict';
import { GameEngine } from '../server/game.js';
import { fireOneShot } from '../server/sim/combat.js';
import { WEAPON_IDS } from '../shared/combatmath.js';
import { parseVehicleAction } from '../server/protocol/admission.js';

let snapshot;
const game = new GameEngine({ mode: 'conquest', mapMeta: { id: 'frontier', dimensions: {sx:128,sy:32,sz:128}, spawns: {conquest:{alpha:[{x:20,y:2,z:20}],bravo:[{x:70,y:2,z:20}]}}, conquest: {flags:[], bases:{}, vehicleSpawns:[{id:'a-tank',team:'alpha',type:'tank',x:20,y:2,z:30,yaw:0},{id:'b-jeep',team:'bravo',type:'jeep',x:20,y:2,z:10,yaw:0}] } }, world: {dimensions:{sx:128,sy:32,sz:128},getBlock:(_x,y)=>y<2?1:0,findSpawns:()=>[{x:20,y:2,z:20}],setBlock:()=>{}}, broadcast:s=>snapshot=s });
game.addClient('a','A'); game.addClient('b','B');
const a=game.entities.get('a'), b=game.entities.get('b');
assert.equal(a.team,'alpha'); assert.equal(b.team,'bravo');
assert.equal(parseVehicleAction({type:'damage',vehicleId:'a-tank'}),null);
assert.equal(parseVehicleAction({type:'enter',vehicleId:'a-tank',hp:100}),null);
Object.assign(a,{x:20,y:2,z:30});
game.applyInput('a',{seq:1,vehicleAction:{type:'enter',vehicleId:'a-tank'},keys:{},vehicleThrottle:1,vehicleSteer:0,yaw:0,pitch:0,wantFire:false});
assert.equal(a.vehicleId,'a-tank');
const initial=game.vehicles.vehicles.get('a-tank').z;
for(let i=0;i<30;i++)game.step();
assert.ok(game.vehicles.vehicles.get('a-tank').z<initial,'authoritative driver moves hull');
assert.equal(snapshot.players.find(p=>p.id==='a').vehicleId,'a-tank');
assert.equal(snapshot.vehicles.length,2);
const vehicle=game.vehicles.vehicles.get('a-tank');const yawBefore=vehicle.yaw;
game.applyInput('a',{seq:2,keys:{},vehicleThrottle:0,vehicleSteer:0.8,yaw:0,pitch:0});
assert.equal(a.input.seq,2);assert.equal(a.input.vehicleThrottle,0);assert.equal(a.input.vehicleSteer,0.8);
for(let i=0;i<12;i++)game.step();
assert.ok(vehicle.yaw<yawBefore,'actual seated wire controls turn the tank');
game.applyInput('a',{seq:3,keys:{},vehicleThrottle:99,vehicleSteer:-99,vehicleBrake:99});
assert.equal(a.input.vehicleBrake,1);assert.equal(a.input.vehicleThrottle,1);assert.equal(a.input.vehicleSteer,-1);
game.applyInput('a',{seq:4,keys:{},vehicleThrottle:NaN,vehicleSteer:Infinity,vehicleBrake:NaN});
assert.equal(a.input.vehicleBrake,undefined);assert.equal(a.input.vehicleThrottle,undefined);assert.equal(a.input.vehicleSteer,undefined);
// Park back on the firing lane after verifying steering.
Object.assign(vehicle,{x:20,speed:0});
const magazine=a.mag.slice();
game.applyInput('a',{keys:{},yaw:0,pitch:-0.12,wantFire:true});
for(let i=0;i<16 && game.projectiles.active.size===0;i++)game.step();
assert.deepEqual(a.mag,magazine,'tank fire does not consume infantry magazine');
assert.ok(game.projectiles.active.size,'tank launches authoritative projectile');
const enemy=game.vehicles.vehicles.get('b-jeep'), health=enemy.hp;
for(let i=0;i<120;i++)game.step();
assert.ok(enemy.hp<health,'tank shell reaches enemy hull');
const own=game.vehicles.vehicles.get('a-tank'); const ownHp=own.hp;
assert.equal(game.vehicles.damage(own.id,100,a,{explosive:true}),false);
assert.equal(own.hp,ownHp,'friendly damage rejected');
game.applyInput('a',{vehicleAction:{type:'exit'},wantFire:false,keys:{}});
assert.equal(a.vehicleId,null); assert.equal(own.occupantId,null);
Object.assign(a,{x:own.x,y:own.y,z:own.z});game.applyInput('a',{vehicleAction:{type:'enter',vehicleId:own.id},keys:{}});
game.vehicles.damage(own.id,10000,b,{explosive:true});
assert.equal(a.state,'dead'); assert.equal(a.vehicleId,null); assert.equal(own.occupantId,null);
game.respawnPlayer(a);assert.equal(a.vehicleId,null);
// Infantry rays stop on the hull and cannot hit the protected driver's body.
Object.assign(b,{x:own.x,y:own.y,z:own.z});game.applyInput('b',{vehicleAction:{type:'enter',vehicleId:own.id},keys:{}});
assert.equal(b.vehicleId,null,'enemy cannot enter team-owned hull');
const jeep=game.vehicles.vehicles.get('b-jeep');jeep.hp=260;
Object.assign(b,{x:jeep.x,y:jeep.y,z:jeep.z});game.applyInput('b',{vehicleAction:{type:'enter',vehicleId:jeep.id},keys:{}});
Object.assign(a,{x:jeep.x,y:jeep.y-0.5,z:jeep.z+10,yaw:0,pitch:0,weapon:WEAPON_IDS.indexOf('rifle')});
a.input={keys:{},yaw:0,pitch:0};const bHp=b.hp;const jeepHp=jeep.hp;
fireOneShot(a,game.contexts.combat,1,{yaw:0,pitch:0});
assert.ok(jeep.hp<jeepHp,'infantry hitscan damages hull');assert.equal(b.hp,bHp,'hull shields occupant');
game.vehicles.release(b);
// A second life releases the seat on transport disconnect.
own.hp=ownHp;Object.assign(a,{x:own.x,y:own.y,z:own.z});game.applyInput('a',{vehicleAction:{type:'enter',vehicleId:own.id},keys:{}});assert.equal(a.vehicleId,own.id);
game.removeClient('a'); assert.equal(own.occupantId,null);
console.log('Conquest server integration: admission, drive, snapshot, tank projectile hull damage, friendly rejection, exit, death, respawn and disconnect verified.');
