#!/usr/bin/env node
// Regenerate the <link rel="modulepreload"> block in public/index.html from the
// static import graph behind public/js/boot.js (plus its dynamic main.js).
// That graph is the menu's critical path only; the match runtime, three.js and
// the Blender library are imported later by the asset scheduler and are not
// preloaded. Without the block the browser discovers the graph level by level;
// with it every critical module is requested as soon as the HTML arrives.
// Usage: node tools/build-module-preload.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const PUBLIC = path.join(ROOT, 'public');
const INDEX = path.join(PUBLIC, 'index.html');
const START = '<!-- modulepreload:start (generated by tools/build-module-preload.mjs) -->';
const END = '<!-- modulepreload:end -->';
const IMPORT_RE = /(?:^|[\n;])\s*(?:import|export)\s+(?:[^'"()]*?\s+from\s+)?['"]([^'"]+)['"]/g;
const DYNAMIC_RE = /import\(\s*['"]([^'"]+)['"]\s*\)/g;

/** Map a served URL path back to the file that serves it (public/ or shared/). */
function fileFor(urlPath) {
  const rel = urlPath.replace(/^\//, '');
  const primary = path.join(PUBLIC, rel);
  if (rel.startsWith('shared/')) {
    const alt = path.join(ROOT, rel);
    try { readFileSync(alt); return alt; } catch { /* fall through */ }
  }
  return primary;
}

export function collectModuleGraph(entry = '/js/boot.js') {
  const seen = new Set();
  const order = [];
  const visit = (urlPath) => {
    if (seen.has(urlPath)) return;
    seen.add(urlPath);
    let source;
    try { source = readFileSync(fileFor(urlPath), 'utf8'); } catch { return; }
    order.push(urlPath);
    const specifiers = [];
    for (const match of source.matchAll(IMPORT_RE)) specifiers.push(match[1]);
    // boot.js hands off to main.js at runtime; preload that graph as well.
    if (urlPath === entry) for (const match of source.matchAll(DYNAMIC_RE)) specifiers.push(match[1]);
    for (const specifier of specifiers) {
      if (!specifier.startsWith('.') && !specifier.startsWith('/')) continue;
      const resolved = specifier.startsWith('/') ? specifier
        : path.posix.normalize(path.posix.join(path.posix.dirname(urlPath), specifier));
      visit(resolved);
    }
  };
  visit(entry);
  return order;
}

export function renderPreloadBlock(modules) {
  const lines = modules.map((href) => `<link rel="modulepreload" href=".${href}">`);
  return `${START}\n<meta name="vb-module-count" content="${modules.length}">\n${lines.join('\n')}\n${END}`;
}

export function updateIndexHtml(html, modules) {
  const block = renderPreloadBlock(modules);
  const start = html.indexOf(START);
  const end = html.indexOf(END);
  if (start >= 0 && end > start) return html.slice(0, start) + block + html.slice(end + END.length);
  return html.replace('</head>', `${block}\n</head>`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const modules = collectModuleGraph();
  const current = readFileSync(INDEX, 'utf8');
  const next = updateIndexHtml(current, modules);
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error('public/index.html modulepreload block is stale; run node tools/build-module-preload.mjs');
      process.exit(1);
    }
    console.log(`modulepreload block is current (${modules.length} modules)`);
  } else {
    writeFileSync(INDEX, next);
    console.log(`wrote ${modules.length} modulepreload links into public/index.html`);
  }
}
