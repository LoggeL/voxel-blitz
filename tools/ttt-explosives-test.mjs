import assert from 'node:assert/strict';
import { GameEngine } from '../server/game.js';
import { TTT_C4, TTT_GRENADES, TTT_GRENADE_CAP } from '../shared/ttt.js';
import { GRENADE_TYPE_IDS } from '../shared/grenade-rules.js';
const game=new GameEngine({mode:'ttt'});
for(const id of ['a','b','c','d'])game.addClient(id,id);
const policy=game.mode.policy,a=game.entities.get('a'),b=game.entities.get('b'),c=game.entities.get('c'),d=game.entities.get('d');
assert.deepEqual(new Set([...policy.pickups.values()].filter(p=>p.grenade).map(p=>p.grenade)),new Set(TTT_GRENADES));
const ground=[...policy.pickups.values()].find(p=>p.grenade==='frag');
Object.assign(a,{x:ground.x,y:ground.y,z:ground.z});
assert.equal(policy.buy(a,`ttt:pickup:${ground.id}`),true);assert.equal(a.grenades[0],1);assert.equal(a.owned.length,0);
assert.equal(policy.canThrow(a),false,'prep grenades cannot be thrown');
const gun=[...policy.pickups.values()].find(p=>p.weapon);Object.assign(a,{x:gun.x,y:gun.y,z:gun.z});
assert.equal(policy.buy(a,`ttt:pickup:${gun.id}`),true);
policy.drop(a);assert.equal(a.grenades[0],1,'dropping a gun preserves grenades');
policy.pickups.set('999',{id:'999',x:a.x,y:a.y,z:a.z,grenade:'frag'});
a.grenades[0]=TTT_GRENADE_CAP;assert.equal(policy.buy(a,'ttt:pickup:999'),false);
a.grenades[0]=1;
game.now=policy.phaseEndsAt;game.mode.tick();
for(const p of [a,b])policy.roles.set(p.id,'traitor');for(const p of [c,d])policy.roles.set(p.id,'innocent');
policy.wallets.set('a',2);policy.wallets.set('c',2);
assert.equal(policy.canFire(a),false);assert.equal(policy.canThrow(a),true,'grenades work without a gun');
a.deployT=0;game.applyInput('a',{throwGrenade:true,grenadeType:GRENADE_TYPE_IDS.indexOf('frag'),grenadeCharge:0,yaw:0,pitch:0});
game.projectiles.step(.05,game.contexts.projectiles);assert.equal(a.grenades[0],0);game.projectiles.clear();
assert.equal(policy.privateState('a').allyPositions[0].id,'b');
b.x+=10;assert.equal(policy.privateState('a').allyPositions[0].x,b.x,'allies update without radar');
assert.deepEqual(policy.privateState('c').allyPositions,[],'innocents receive no ally tracking');
assert.equal(policy.buy(c,'ttt:c4'),false);assert.equal(policy.buy(a,'ttt:c4'),true);
assert.equal(policy.buy(a,'ttt:c4'),false,'one C4 per round');
for(const p of [a,b,c,d]){Object.assign(p,{x:30.5,y:20,z:30.5,grounded:true,spawnProtectedUntil:0});}
// Use a cleared open patch, with separate nearby and distant targets.
for(let x=25;x<48;x++)for(let z=25;z<48;z++)for(let y=19;y<24;y++)game.world.setBlock(x,y,z,y===19?1:0);
b.x=45;c.x=32;d.z=45;
a.grounded=false;assert.equal(policy.buy(a,'ttt:c4-place'),false);a.grounded=true;
assert.equal(policy.buy(a,'ttt:c4-place'),true);assert.equal(policy.buy(a,'ttt:c4-place'),false);
const bomb=policy.equipment.bombSnapshot()[0];assert.equal(bomb.explodeAt-game.now,TTT_C4.fuseMs);
a.state='dead';policy.onPlayerDeath(a);assert.equal(policy.equipment.bombs.size,1,'planted C4 survives its owner');
game.now=bomb.explodeAt-1;policy.equipment.tick();assert.equal(c.state,'alive');
game.now++;policy.equipment.tick();assert.equal(policy.equipment.bombs.size,0);assert.equal(c.state,'dead','C4 applies real blast damage');
assert.equal(d.state,'alive','distant players survive');
assert.ok(game.tickEvents.some(e=>e.kind==='projectileExplode'&&e.type==='c4'));
assert.equal([...policy.corpses.values()].find(p=>p.playerId==='c').weapon,'c4');
policy.equipment.clear();assert.equal(policy.equipment.bombSnapshot().length,0);
console.log('TTT explosives/allies: random grenades, pickup caps, unarmed throws, private live ally positions, C4 authorization/timer/owner death/real damage passed.');
