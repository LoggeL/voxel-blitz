import assert from 'node:assert/strict';
import { GameEngine } from '../server/game.js';
import { LobbyManager } from '../server/lobby.js';
import { parseBuyFrame } from '../server/protocol/admission.js';
const game=new GameEngine({mode:'ttt'});
for(const id of ['a','b','c','d'])game.addClient(id,`Operator ${id}`);
const policy=game.mode.policy, a=game.entities.get('a'),b=game.entities.get('b');
game.now=policy.phaseEndsAt;game.mode.tick();
policy.roles.set('a','innocent');policy.roles.set('b','traitor');policy.roles.set('c','traitor');policy.roles.set('d','innocent');
Object.assign(a,{x:20.5,y:15,z:20.5});Object.assign(b,{x:21.5,y:15,z:20.5});
game.killPlayer(b,a,'rifle',false);
const body=[...policy.corpses.values()][0];
assert.ok(body);assert.equal(body.role,'traitor');
let snapshot=policy.matchSnapshot();
assert.equal(snapshot.corpses[0].role,undefined);assert.equal(snapshot.corpses[0].name,undefined);
assert.equal(snapshot.corpses[0].playerId,undefined);assert.equal(snapshot.revealedRoles,undefined);
assert.equal(policy.buy(b,`ttt:inspect:${body.id}`),false,'dead players cannot inspect');
a.x=30;assert.equal(policy.buy(a,`ttt:inspect:${body.id}`),false,'distance is authoritative');
a.x=19.5;game.world.setBlock(20,15,20,1);
assert.equal(policy.buy(a,`ttt:inspect:${body.id}`),false,'walls prevent inspection');
game.world.setBlock(20,15,20,0);a.x=20.5;
assert.equal(policy.buy(a,`ttt:inspect:${body.id}`),true);
assert.equal(policy.buy(a,`ttt:inspect:${body.id}`),true,'repeat inspection is harmless');
snapshot=policy.matchSnapshot();
assert.equal(snapshot.corpses[0].playerId,'b');
assert.equal(game.tickEvents.filter(e=>e.kind==='body_identified').length,1,'repeated inspection announces once');
assert.equal(game.tickEvents.find(e=>e.kind==='body_identified').inspectorName,'Operator a');
assert.equal(snapshot.corpses[0].name,'Operator b');assert.equal(snapshot.corpses[0].role,'traitor');
assert.equal(snapshot.corpses[0].weapon,'rifle');assert.equal(snapshot.revealedRoles,undefined);
assert.equal(parseBuyFrame({t:'buy',weapon:`ttt:inspect:${body.id}`}),`ttt:inspect:${body.id}`);
assert.equal(parseBuyFrame({t:'buy',weapon:'ttt:inspect:../b'}),null);
assert.equal(policy.buy(a,'ttt:inspect:99999'),false);
const manager=Object.create(LobbyManager.prototype);const delivered=[];manager.sendJson=(_meta,msg)=>delivered.push(msg);
manager._broadcastJson({engine:game,members:new Map([['a',{id:'a',meta:{}}]])},{t:'tick',players:[],events:game.tickEvents});
assert.ok(game.tickEvents.some(e=>e.kind==='kill'),'internal kill still exists for game bookkeeping');
assert.ok(!delivered[0].events.some(e=>e.kind==='kill'),'TTT sends no killfeed payload');
assert.ok(delivered[0].events.some(e=>e.kind==='body_identified'),'body announcements reach clients');
assert.ok(delivered[0].events.some(e=>e.kind==='die'),'death presentation remains available');
policy.onPlayerRemove(b);game.entities.delete('b');
assert.equal(policy.corpses.size,1,'disconnect does not remove a body');
policy.phase='post';snapshot=policy.matchSnapshot();
assert.equal(snapshot.roleRoster.find(p=>p.id==='b').name,'Operator b');
assert.equal(snapshot.revealedRoles.b,'traitor','post-match reveals departed traitors');
policy.tick();assert.equal(policy.corpses.size,0);assert.equal(policy.participants.size,0);
assert.equal(policy.matchSnapshot().revealedRoles,undefined);
console.log('TTT bodies: hidden identity, inspection, distance/walls/life checks, death causes, no killfeed, disconnect retention and round reset passed.');
