import assert from 'node:assert/strict';
import { GameEngine } from '../server/game.js';
import { LobbyManager } from '../server/lobby.js';
import { LocalPlayer } from '../public/js/player/local-player.js';
import { parseBuyFrame } from '../server/protocol/admission.js';
import { TTT_GADGET_RULES } from '../shared/ttt.js';

const game = new GameEngine({ mode: 'ttt' });
for (const id of ['a','b','c','d']) game.addClient(id,id);
const policy=game.mode.policy;
game.now=policy.phaseEndsAt;game.mode.tick();
const p=game.entities.get('a'), enemy=game.entities.get('b');
policy.roles.set('a','traitor');for(const id of ['b','c','d'])policy.roles.set(id,'innocent');
policy.wallets.set('a',10);
assert.equal(policy.buy(enemy,'ttt:radar'),false);
assert.equal(policy.buy(p,'ttt:radar'),true);
assert.equal(policy.privateState('a').equipment.includes('radar'),true);
assert.equal(policy.privateState('a').radar.contacts.length,3);
assert.equal(policy.buy(p,'ttt:radar'),false,'single-purchase gadget rejects duplicates');
assert.equal(policy.privateState('a').credits,9);
const frozen=policy.privateState('a').radar;
enemy.x+=8;
game.now=frozen.nextScanAt-1;policy.equipment.tick();assert.deepEqual(policy.privateState('a').radar,frozen);
const modified=policy.privateState('a').radar;modified.contacts[0].x=-500;
assert.notEqual(policy.privateState('a').radar.contacts[0].x,-500,'private payload has no alias into authority');
game.now++;policy.equipment.tick();assert.equal(policy.privateState('a').radar.contacts[0].x,enemy.x);
assert.equal(policy.privateState('a').radar.contacts[0].ally,false);
assert.equal(policy.buy(p,'ttt:disguiser'),true);assert.equal(policy.equipment.isDisguised('a'),true);
assert.equal(policy.buy(enemy,'ttt:disguise-on'),false);
assert.equal(policy.buy(p,'ttt:disguise-off'),true);assert.equal(policy.equipment.isDisguised('a'),false);
assert.equal(policy.buy(p,'ttt:disguise-on'),true);
// Two valid floor pads used as independent mark/return endpoints.
for(const x of [20,30])for(let dx=-2;dx<=2;dx++)for(let dz=-2;dz<=2;dz++)for(let y=14;y<=18;y++)game.world.setBlock(x+dx,y,20+dz,y===14?1:0);
Object.assign(p,{x:20.5,y:15,z:20.5,grounded:true,hp:43,armor:17});
assert.equal(policy.buy(p,'ttt:teleport-return'),false,'unowned teleporter rejects actions');
assert.equal(policy.buy(p,'ttt:teleporter'),true);
assert.equal(policy.buy(p,'ttt:teleport-return'),false,'mark is required');
assert.equal(policy.buy(p,'ttt:teleport-mark'),true);
p.x=30.5;
game.world.setBlock(20,15,20,1);
assert.equal(policy.buy(p,'ttt:teleport-return'),false,'blocked mark cannot be entered');
assert.equal(policy.privateState('a').teleporter.uses,3);
game.world.setBlock(20,15,20,0);
Object.assign(enemy,{x:20.5,y:15,z:20.5});
assert.equal(policy.buy(p,'ttt:teleport-return'),false,'occupied destination does not telefrag or overlap');
enemy.x=40;
p.grounded=false;assert.equal(policy.buy(p,'ttt:teleport-return'),false);p.grounded=true;
assert.equal(policy.buy(p,'ttt:teleport-return'),true);assert.equal(p.x,20.5);
assert.equal(p.hp,43);assert.equal(p.armor,17);assert.equal(p.lives,2,'teleport does not respawn or grant a fresh life');
assert.equal(policy.privateState('a').teleporter.uses,2);
assert.equal(policy.buy(p,'ttt:teleport-return'),false,'rapid repeat is blocked by cooldown');
assert.equal(policy.privateState('a').teleporter.cooldown,20);
for(let i=0;i<2;i++){game.now+=TTT_GADGET_RULES.teleportCooldownMs;assert.ok(policy.buy(p,'ttt:teleport-return'));}
game.now+=TTT_GADGET_RULES.teleportCooldownMs;
assert.equal(policy.buy(p,'ttt:teleport-return'),false,'finite charges');
// Production wire: gadget inventory, radar targets, and mark go only to their owner.
let snapshot;game.broadcast=s=>snapshot=s;game.step(50);
const deliveries=[];const manager=Object.create(LobbyManager.prototype);manager.sendJson=(meta,data)=>deliveries.push([meta.id,data]);
manager._broadcastJson({engine:game,members:new Map([...game.entities].map(([id])=>[id,{id,meta:{id}}]))},snapshot);
const wire=deliveries.find(([id])=>id==='b')[1];
assert.equal(wire.players.find(p=>p.id==='a').disguised,true);
assert.equal(wire.players.find(p=>p.id==='a').ttt,undefined);
assert.ok(!JSON.stringify(wire).includes('"contacts"'));
assert.equal(policy.privateState('b').radar,undefined);
// A displacement is adopted once without changing health, inventory or medkits.
const local=new LocalPlayer({ input: { setGameplayEnabled() {}, consumeDelta() { return { x: 0, y: 0 }; }, getKeys() { return {}; } } });local.respawn({x:30.5,y:15,z:20.5});
const row=deliveries.find(([id])=>id==='a')[1].players.find(p=>p.id==='a');
local.reconcile(row,1);assert.equal(local.pos.x,row.x);assert.equal(local.hp,43);
assert.equal(local.reconcileOffset.x,0);
local.dispose();
assert.equal(parseBuyFrame({t:'buy',weapon:'ttt:teleport-mark'}),'ttt:teleport-mark');
assert.equal(parseBuyFrame({t:'buy',weapon:'ttt:teleport-return',x:1}),null,'destination cannot be supplied by clients');
p.state='dead';policy.onPlayerDeath(p);assert.equal(policy.equipment.isDisguised('a'),false);
assert.equal(policy.privateState('a').radar,undefined);assert.equal(policy.buy(p,'ttt:teleport-return'),false);
policy.phase='prep';assert.equal(policy.buy(enemy,'ttt:radar'),false);
policy.equipment.clear();assert.equal(policy.equipment.players.size,0);
console.log('TTT equipment: scan interval and frozen contacts, private wire, duplicate purchases, disguise, safe teleport/cooldown/charges, client relocation and lifecycle passed');
